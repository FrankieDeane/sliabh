const DIFF_COLOR: Record<string, string> = {
  facil: '#22c55e',
  moderado: '#f59e0b',
  dificil: '#ef4444',
  extremo: '#a855f7',
};
const DIFF_LABEL: Record<string, string> = {
  facil: 'Fácil',
  moderado: 'Moderado',
  dificil: 'Difícil',
  extremo: 'Extremo',
};

// ─── Route Picker Modal ───────────────────────────────────────────────────────

function RoutePicker({
  visible,
  onClose,
  onSelect,
  c,
}: {
  visible: boolean;
  onClose: () => void;
  onSelect: (t: ArgentinaTrail) => void;
  c: ThemeColors;
}) {
  const [search, setSearch] = React.useState('');
  const filtered = useMemo(
    () => ARGENTINA_TRAILS.filter(
      (t) =>
        t.name.toLowerCase().includes(search.toLowerCase()) ||
        t.province.toLowerCase().includes(search.toLowerCase())
    ),
    [search]
  );

  return (
    <Modal visible={visible} transparent animationType="slide" onRequestClose={onClose}>
      <TouchableOpacity style={pickerStyles.backdrop} activeOpacity={1} onPress={onClose}>
        <TouchableOpacity activeOpacity={1} style={[pickerStyles.sheet, { backgroundColor: c.surface, borderColor: c.border }]}>
          <View style={[pickerStyles.handle, { backgroundColor: c.border }]} />
          <Text style={[pickerStyles.title, { color: c.text }]}>Elegir ruta</Text>

          {/* Search */}
          <View style={[pickerStyles.searchWrap, { backgroundColor: c.elevated, borderColor: c.border }]}>
            <Ionicons name="search-outline" size={16} color={c.muted} />
            {Platform.OS === 'web' ? (
              // @ts-ignore
              <input
                value={search}
                onChange={(e: any) => setSearch(e.target.value)}
                placeholder="Buscar ruta o provincia…"
                style={{
                  flex: 1, background: 'transparent', border: 'none', outline: 'none',
                  color: c.text, fontSize: 14, fontFamily: 'inherit',
                }}
              />
            ) : (
              <Text style={{ color: c.muted, flex: 1 }}>Buscar…</Text>
            )}
          </View>

          <ScrollView showsVerticalScrollIndicator={false} style={{ maxHeight: 460 }}>
            {filtered.map((trail) => (
              <TouchableOpacity
                key={trail.id}
                style={[pickerStyles.item, { borderBottomColor: c.border }]}
                onPress={() => { onSelect(trail); onClose(); }}
                activeOpacity={0.7}
              >
                <View style={[pickerStyles.diffDot, { backgroundColor: DIFF_COLOR[trail.difficulty] }]} />
                <View style={{ flex: 1 }}>
                  <Text style={[pickerStyles.itemName, { color: c.text }]}>{trail.name}</Text>
                  <Text style={[pickerStyles.itemSub, { color: c.muted }]}>
                    {trail.province} · {trail.distance_km} km · {DIFF_LABEL[trail.difficulty]}
                  </Text>
                </View>
                <Ionicons name="chevron-forward" size={16} color={c.muted} />
              </TouchableOpacity>
            ))}
          </ScrollView>
        </TouchableOpacity>
      </TouchableOpacity>
    </Modal>
  );
}

